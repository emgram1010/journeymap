// OBS-1 (US-OBS-1-12 — correlation-id spike) — DECISION RECORDED HERE:
// XanoScript has no documented "middleware" construct that could attach
// a correlation id to every request automatically (confirmed by reading
// the XanoScript syntax reference; no "middleware" keyword appears
// anywhere in it). So this epic uses the fallback the epic itself names:
// an explicit id generated by the CLIENT, sent as a request header, and
// echoed back by endpoints that call ops/log_event.
export const CORRELATION_HEADER = 'X-Correlation-Id';

/** Generates one correlation id, shown to the user as "Reference" on errors. */
export function newCorrelationId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  // Fallback for environments without crypto.randomUUID (older browsers,
  // some test runners). Not cryptographically strong — fine for a
  // display/correlation id, not for anything security-sensitive.
  return `cid-${Date.now()}-${Math.random().toString(16).slice(2)}`;
}
