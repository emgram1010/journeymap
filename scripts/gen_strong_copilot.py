"""COP-13 part B - generates the STRONG copy of the copilot agent from the standard one, so the two can
never drift. The only differences: the agent's name, the model, no canonical/guid (Xano assigns its own),
and no request_step_up tool (the strong copy never asks again). Run after every edit to
ai/agent/emgram_copilot.xs:  python scripts/gen_strong_copilot.py
A unit test (UT-COP-13-B-02) fails if the files differ in anything else.
"""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "ai/agent/emgram_copilot.xs").read_text(encoding="utf-8")
out = []
out.append("// COP-13 part B - GENERATED by scripts/gen_strong_copilot.py from ai/agent/emgram_copilot.xs. Do not edit;\n")
out.append("// edit the standard copy and regenerate. Runs only when a step-up was allowed (request_step_up).\n")
for line in src.splitlines(keepends=True):
    if re.match(r"^\s*//", line):
        continue
    if line.startswith('agent "Emgram Copilot"'):
        line = 'agent "Emgram Copilot Strong" {\n'
    elif re.match(r'^\s*canonical\s*=', line) or re.match(r'^\s*guid\s*=', line):
        continue
    elif re.match(r'^\s*model\s*:', line):
        line = re.sub(r'"[^"]+"', '"claude-opus-5-5"', line, count=1)
    elif '{name: "request_step_up"}' in line:
        continue
    out.append(line)
dst = root / "ai/agent/emgram_copilot_strong.xs"
dst.write_text("".join(out), encoding="utf-8")
print("wrote", dst.relative_to(root))
